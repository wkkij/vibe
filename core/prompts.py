def classify_task(text: str) -> str:
    t = (text or "").lower()
    for kind, pat in KIND_PATTERNS:
        if re.search(pat, t):
            return kind
    return "general"


class PromptBook:
    """Собирает текст промптов. В режиме auto каждое сообщение формулируется по-новому и зависит от типа задачи."""

    def __init__(self, style: str = "auto", seed: Optional[int] = None):
        self.rng = random.Random(seed)
        self.style = style if style in VALID_STYLES else "auto"
        self.kind = "general"
        self._last: Dict[str, int] = {}

    def set_style(self, style: str) -> None:
        self.style = style if style in VALID_STYLES else "auto"

    @property
    def current(self) -> str:
        return self.style

    def begin_task(self, user_task: str = "") -> str:
        self.kind = classify_task(user_task)
        return self.kind

    # --- выбор формулировки ---
    def _pick(self, key: str, pool: List[str]) -> str:
        n = len(pool)
        if n == 1:
            return pool[0]
        prev = self._last.get(key, -1)
        idx = self.rng.choice([i for i in range(n) if i != prev])
        self._last[key] = idx
        return pool[idx]

    def _t(self, key: str) -> str:
        if self.style == "classic":
            return CLASSIC[key]
        return self._pick(key, POOLS[key])

    def _hint(self) -> str:
        if self.style == "classic":
            return ""
        pool = KIND_HINTS.get(self.kind) or KIND_HINTS["general"]
        return self._pick("hint:" + self.kind, pool)

    # --- системные инструкции ---
    def system_patcher(self, auto_context: bool = False) -> str:
        rules = PATCH_FORMAT_RULES + ("\n" + AUTO_CONTEXT_RULE if auto_context else "")
        hint = self._hint()
        return f"{self._t('intro')}\n\n{rules}\n\n{self._t('outro')}" + (f"\n{hint}" if hint else "") + "\n"

    def system_planner(self) -> str:
        hint = self._hint()
        return f"{self._t('plan_intro')}\n\n{PLAN_BODY}\n\n{self._t('plan_outro')}" + (f"\n{hint}" if hint else "") + "\n"

    # --- сообщения ---
    def task(self, user_task: str) -> str:
        return self._t("task").format(task=user_task)

    def plan_task(self, user_task: str) -> str:
        return self._t("plan_task").format(task=user_task)

    def plan_approved(self) -> str:
        return self._t("approve")

    def plan_revise(self, notes: str) -> str:
        return self._t("revise").format(notes=notes)

    def heal(self, cmd: str, log: str) -> str:
        return self._t("heal").format(cmd=cmd, log=log)

    def repair(self, parts: str) -> str:
        return self._t("repair").format(parts=parts)

    def need_files(self, files: str) -> str:
        return self._t("need_files").format(files=files)

    def continue_after_stop(self) -> str:
        return self._t("cont")

    def dirty_sync(self, fresh: str, task: str) -> str:
        return self._t("dirty").format(fresh=fresh, task=task)

    def canary(self, canary: str) -> str:
        return self._pick("canary", CANARY_VARIANTS).format(canary=canary)


def describe_styles() -> List[Dict[str, str]]:
    return [{"id": k, "title": STYLE_TITLES[k]} for k in VALID_STYLES]
